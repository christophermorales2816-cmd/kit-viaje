-- Kuwait, con la Ciudad de Kuwait como base. Precios en dinares kuwaitíes, con
-- centavos (fils): el dinar vale más de tres dólares, y un café cuesta menos de
-- una unidad.
--
-- Un país chico de desierto sobre el Golfo, y de los más calurosos del mundo en
-- verano: de junio a agosto las máximas pasan los cuarenta y cinco grados en la
-- ciudad y más en el interior, como en Jahra. El invierno es templado y corto,
-- con algo de lluvia. La costa, en Salmiya, Fahaheel o la isla Failaka, es un
-- poco menos extrema.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Jahra en enero: 7 / 19,6 → frio + fresco + templado → abrigo, cero playa
--   Jahra en julio: 30 / 47,4 → calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000006900 a 6908, la base es 6900.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

