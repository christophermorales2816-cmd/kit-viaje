-- Filipinas, con Manila como ciudad base. Precios en pesos filipinos, sin centavos.
--
-- Más de siete mil islas en el trópico: calor todo el año. En el oeste (Manila,
-- Palawan, Boracay) la estación seca va de diciembre a mayo y la de lluvias, de
-- junio a noviembre, con tifones sobre todo de julio a octubre. Siargao, en la
-- costa del Pacífico, tiene la lluvia al revés: de noviembre a febrero. Banaue,
-- en la cordillera, es la única fresca.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Banaue en enero: 13,4 / 22,4 → fresco + templado → capas, cero playa
--   Manila en abril: 25,2 / 33,6 → calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000005900 a 5908, la base es 5900.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

