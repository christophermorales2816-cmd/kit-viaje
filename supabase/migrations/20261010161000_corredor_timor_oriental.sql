-- Timor Oriental, con Dili como ciudad base. Dolarizado, como Ecuador: el
-- dólar es la moneda oficial, con monedas propias (centavos) para los montos
-- chicos.
--
-- Tropical con una estación seca larga. En la costa norte, en Dili, Baucau y
-- Atauro, hace calor todo el año y llueve de diciembre a marzo; de mayo a
-- octubre casi no llueve. Las montañas del centro, en Maubisse y al pie del
-- Ramelau, a más de mil quinientos metros, son frescas, con noches frías en
-- julio y agosto y más lluvia.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Monte Ramelau (Hato Builico) en agosto: 5,8 / 18,2 → frio + fresco + templado → abrigo, cero playa
--   Dili en noviembre: 23,8 / 32,2 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000007100 a 7108, la base es 7100.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

