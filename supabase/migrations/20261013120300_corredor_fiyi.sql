-- Precios en dólares fiyianos, sin centavos: valen menos de medio dólar.
--
-- Las ciudades del planificador son las de Viti Levu —Nadi, Denarau, la Costa
-- de Coral, Pacific Harbour y Suva—, las islas Mamanuca y Yasawa, y Savusavu y
-- Taveuni, en el norte. Taveuni queda al este del meridiano 180: es el primer
-- destino del planificador del otro lado del antimeridiano (spec, 16.4).
--
-- Calor húmedo todo el año, con una temporada de lluvias y ciclones de
-- noviembre a abril. El oeste, donde están Nadi y las islas, es más seco; el
-- este, con Suva y Taveuni, llueve casi todo el año.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
