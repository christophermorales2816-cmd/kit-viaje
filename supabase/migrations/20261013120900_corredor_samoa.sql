-- Samoa, con Apia como ciudad base: es la capital, en Upolu, y por donde
-- entra casi todo el que viaja. Precios en talas, sin centavos.
--
-- Las ciudades del planificador son las de Upolu —Apia, To Sua, Lalomanu, Piula
-- y la isla de Manono— y las de Savai'i: Salelologa, Manase, los campos de lava
-- de Saleaula y los agujeros de Alofaaga.
--
-- Calor húmedo todo el año, con la temporada de lluvias y ciclones de noviembre
-- a abril. De mayo a octubre llueve menos y sopla el alisio, aunque los
-- chaparrones siguen. Samoa está al oeste de la línea de cambio de fecha: tiene
-- trece horas más que Greenwich, y en Samoa Americana, a cien kilómetros, es el
-- día anterior.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Apia en julio: 22,6 / 29,2 → templado + calido → nunca abrigo, playa
--   Saleaula (campos de lava) en marzo: 23,6 / 30,6 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000c800 a c808, la base es c800.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

