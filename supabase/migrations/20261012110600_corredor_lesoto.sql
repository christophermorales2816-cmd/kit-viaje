-- Lesoto, con Maseru como ciudad base: es la capital y por donde entra casi
-- todo el que viaja. Precios en maloti —el plural de loti—, sin centavos: el
-- loti vale lo mismo que el rand, que también se acepta en todo el país.
--
-- Todo el país está por encima de los mil cuatrocientos metros, y el clima lo
-- manda la altura. Los veranos, de noviembre a marzo, son templados y con
-- tormentas de tarde; los inviernos, secos y fríos, con heladas en todo el país
-- y nieve en las montañas. En Maseru, las noches de julio bajan de cero; en
-- Afriski, a más de tres mil metros, rondan los ocho bajo cero y se esquía de
-- junio a agosto.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Afriski (montañas Maluti) en julio: -8,4 / 4 → frio → abrigo, cero playa
--   Maseru en enero: 14,8 / 28,8 → fresco + templado + calido → capas, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000a300 a a308, la base es a300.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

