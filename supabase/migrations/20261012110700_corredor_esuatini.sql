-- Esuatini, con el valle de Ezulwini como ciudad base: es el centro turístico,
-- entre Mbabane, la capital, y Manzini, y donde se aloja buena parte de los que
-- viajan. Precios en emalangeni —el plural de lilangeni—, sin centavos: el
-- lilangeni vale lo mismo que el rand, que también se acepta en todo el país.
--
-- Un país chico con tres climas, de oeste a este. El highveld —Mbabane,
-- Malolotja, Piggs Peak— es fresco y con niebla, con lluvias de verano; el
-- middleveld, en Ezulwini y Manzini, es templado; el lowveld del este, en Hlane
-- y Mkhaya, es caluroso y seco, con la mejor época para los safaris en el
-- invierno, de mayo a septiembre.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Reserva de Malolotja en julio: 3 / 16,8 → frio + fresco → abrigo, cero playa
--   Reserva de Mkhaya en enero: 19,8 / 31,8 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000a400 a a408, la base es a400.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

