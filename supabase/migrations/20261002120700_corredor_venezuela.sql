-- Venezuela, con Caracas como ciudad base. Precios en DÓLARES.
--
-- El país tiene moneda propia, el bolívar, y dos cotizaciones que pueden estar
-- lejos entre sí. Pero los precios del planificador se cargan en dólares, por dos
-- razones: es como se le cobra a un viajero, y con la inflación del bolívar un
-- precio en moneda local quedaría viejo en semanas. destinations.base_currency es
-- USD; el corredor de cotizaciones sigue siendo VES, porque eso es lo que la guía
-- explica. budgetConversionStatus resuelve el cruce.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Colonia Tovar en enero: 11,4 / 20,4 → fresco + templado → capas, cero playa
--   Morrocoy en septiembre: 25,4 / 32,8 → calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000001600 a 1608, la base es 1600.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

