-- Panamá, con Ciudad de Panamá como ciudad base. Dolarizado.
--
-- El balboa existe pero solo en monedas: los billetes que circulan son dólares.
-- Calor húmedo todo el año al nivel del mar; Boquete, en las tierras altas, es
-- lo único templado. La estación seca del Pacífico va de enero a abril; Bocas del
-- Toro, en el Caribe, tiene su propio calendario y sus meses secos son
-- septiembre y octubre.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Boquete en enero: 14,2 / 24,4 → fresco + templado → capas, cero playa
--   Pedasí en marzo: 23,2 / 32,8 → templado + calido → nunca abrigo, playa
--
