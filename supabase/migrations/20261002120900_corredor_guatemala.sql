-- Guatemala, con Antigua como ciudad base.
--
-- Es la única base que no es la capital, y a propósito: el aeropuerto está en
-- Ciudad de Guatemala pero casi todos los viajeros duermen la primera noche en
-- Antigua, a una hora. El altiplano es templado de día y frío de madrugada; Petén
-- y el Caribe son calor húmedo. La estación de lluvias va de mayo a octubre y
-- llueve de tarde.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Quetzaltenango en enero: 3,4 / 22 → frio + fresco + templado → abrigo, cero playa
--   Tikal y Flores en mayo: 22,4 / 34,4 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000001800 a 1808, la base es 1800.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

