-- Costa de Marfil, con Abiyán como ciudad base: es la ciudad más grande, el
-- centro económico y por donde entra casi todo el que viaja; Yamusukro, la
-- capital, se visita desde ahí. Precios en francos CFA de África Occidental, sin
-- centavos, la misma moneda que Senegal.
--
-- Calor húmedo todo el año en la costa, con dos temporadas de lluvia: la larga,
-- de abril a julio, con junio como el mes más lluvioso, y la corta, de octubre a
-- noviembre. Hacia el centro, en Yamusukro y Bouaké, el clima es más seco, con
-- el harmattan de diciembre a febrero.
--
-- Las ciudades son las de la costa y del centro. Ninguna está en el norte, cerca
-- de las fronteras con Malí y Burkina Faso, donde las recomendaciones de viaje
-- piden no ir.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Bouaké en diciembre: 20 / 31 → templado + calido → nunca abrigo, playa
--   Yamusukro en febrero: 22,4 / 33,6 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000a100 a a108, la base es a100.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

