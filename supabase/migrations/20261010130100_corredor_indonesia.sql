-- Indonesia, con Ubud (Bali) como ciudad base. Precios en rupias, sin centavos.
--
-- La base es Ubud y no Yakarta, como Antigua en Guatemala: casi todos los que
-- viajan por turismo duermen en Bali y pasan por la capital solo en tránsito.
--
-- Casi todo el país está al sur del ecuador: la estación seca va de abril a
-- octubre y la de lluvias, de noviembre a marzo. Hace calor todo el año salvo en
-- la altura: en el mirador del Bromo, a más de dos mil metros, las noches de
-- julio y agosto son frías. El lago Toba, en Sumatra, está al norte del ecuador
-- y tiene la lluvia repartida en el año, igual que Raja Ampat.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Monte Bromo en julio: 6,6 / 17,6 → frio + fresco → abrigo, cero playa
--   Yakarta en septiembre: 25 / 33 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000005600 a 5608, la base es 5600.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

