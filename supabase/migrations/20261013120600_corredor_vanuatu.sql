-- Yasur, Espíritu Santo, Pentecostés, Malekula y Ambrym.
--
-- Calor húmedo de noviembre a abril, la temporada de lluvias y ciclones, y una
-- temporada más seca y fresca de mayo a octubre. Espíritu Santo, en el norte,
