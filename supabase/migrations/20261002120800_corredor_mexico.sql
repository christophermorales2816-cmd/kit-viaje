-- México, con Ciudad de México como ciudad base.
--
-- La capital está a 2.240 metros: días templados, noches frías en invierno y
-- lluvia de tarde casi todos los días entre junio y septiembre. A dos horas de
-- vuelo, el Caribe de Cancún no baja de 20 grados en todo el año. La temporada
-- de lluvias del Caribe coincide con la de huracanes.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   San Cristóbal de las Casas en enero: 4,2 / 20 → frio + fresco + templado → abrigo, cero playa
--   Mérida en mayo: 22,8 / 36,4 → templado + calido → nunca abrigo, playa
--
