-- Seychelles, con Victoria, en Mahé, como ciudad base: es la capital, a pocos
-- kilómetros del único aeropuerto internacional. Precios en rupias de
-- Seychelles, sin centavos. Muchos hoteles y excursiones se cotizan en euros o
-- en dólares; el planificador los lleva a rupias.
--
-- Trópico casi sobre el ecuador: calor todo el año, sin invierno. Lo que cambia
-- son los vientos y la lluvia. De diciembre a marzo sopla el monzón del noroeste,
-- con más lluvia y mar calmo; de mayo a septiembre, los alisios del sudeste,
-- más secos y con mar movido en algunas playas. Abril, mayo, octubre y
-- noviembre, los meses de cambio, son los más tranquilos. Las islas exteriores,
-- como Desroches, son más secas que las graníticas.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
