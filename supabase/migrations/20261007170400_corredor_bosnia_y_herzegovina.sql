-- con inviernos fríos y nevados; Herzegovina, en el sur, con Mostar y Trebinje,
-- es mediterránea y de las zonas más calurosas de Europa en verano. Jahorina, la
-- montaña olímpica de Sarajevo, es lo más frío.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
