-- leen igual en cualquiera de las dos monedas.
--
-- Un archipiélago: las nueve ciudades son islas o pueblos de islas distintas,
-- de Gran Bahama y Ábaco, que en invierno tienen las noches más frescas, a
-- Exuma, al sur. Casi todo se importa, y los precios lo muestran.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Freeport (Gran Bahama) en enero: 15,5 / 24,5 → fresco + templado → capas, cero playa
--   Andros en agosto: 24 / 32,2 → templado + calido → nunca abrigo, playa
--
