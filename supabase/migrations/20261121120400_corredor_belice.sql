-- Belice, con San Pedro, en el cayo Ambergris, como ciudad base: es donde
-- duerme la mayoría de los viajeros, como Antigua en Guatemala (spec, 13.5).
-- Precios en dólares de Belice, con centavos: valen medio dólar estadounidense
-- por paridad fija, y se cobran en mitades.
--
-- Calor todo el año, con la meseta de Mountain Pine Ridge como lo más fresco
-- y Punta Gorda, en el sur, como lo más lluvioso. Entra con aviso (spec, 22):
-- ninguna de las nueve ciudades está en Ciudad de Belice.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Mountain Pine Ridge en enero: 14 / 24 → fresco + templado → capas, cero playa
--   San Ignacio en mayo: 22 / 34 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000e300 a e308, la base es e300.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

