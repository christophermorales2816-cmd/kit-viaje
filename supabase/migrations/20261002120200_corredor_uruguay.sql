-- Un país chico, de costa y de cuatro estaciones de verdad: el verano se va a la
-- playa y el invierno es húmedo y ventoso, sin nieve pero con un frío que se
-- siente más de lo que marca el termómetro. Es el país más caro de la región
-- para un viajero, y el factor de Punta del Este y José Ignacio lo dice.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Carmelo en julio: 5,2 / 15,2 → frio + fresco → abrigo, cero playa
--   Salto en enero: 19 / 32,4 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000001100 a 1108, la base es 1100.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

