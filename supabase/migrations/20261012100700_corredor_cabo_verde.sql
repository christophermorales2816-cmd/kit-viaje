-- Cabo Verde, con Santa Maria, en la isla de Sal, como ciudad base: es donde
-- llega y se aloja la mayoría de los que viajan; Praia, la capital, está en
-- Santiago. Precios en escudos caboverdianos, sin centavos: el escudo está atado
-- al euro y vale bastante menos que un dólar.
--
-- Diez islas frente a Senegal, en pleno Atlántico. Casi no llueve: un poco de
-- agosto a octubre, más en las islas montañosas y en las laderas que miran al
-- norte. Hace calor templado todo el año, con alisios constantes, que en Sal y
-- Boa Vista hacen del kitesurf el deporte local. La excepción es Chã das
-- Caldeiras, adentro del volcán de Fogo, a casi 1.700 metros, con noches que
-- bajan de once grados.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Chã das Caldeiras (Fogo) en febrero: 10 / 20,8 → frio + fresco + templado → abrigo, cero playa
--   Tarrafal (Santiago) en septiembre: 25,2 / 31 → calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000009c00 a 9c08, la base es 9c00.
