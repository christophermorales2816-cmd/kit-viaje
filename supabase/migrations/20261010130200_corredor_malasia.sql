-- el ringgit vale un cuarto de dólar, como el zloty.
--
-- Ecuatorial: calor y humedad todo el año, con chaparrones casi diarios por la
-- tarde. Lo que cambia según la costa es el monzón: el este de la península
-- (las islas Perhentian) recibe las lluvias fuertes de noviembre a febrero, y
-- muchos alojamientos cierran; el oeste (Penang, Langkawi) llueve más de abril a
-- octubre. Las Tierras Altas de Cameron, a más de mil quinientos metros, son
-- frescas todo el año.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Tierras Altas de Cameron en enero: 14 / 22 → fresco + templado → capas, cero playa
--   Langkawi en marzo: 24,4 / 33,8 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000005700 a 5708, la base es 5700.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

