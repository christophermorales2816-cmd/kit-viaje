-- y mil quinientos metros, tienen veranos calurosos y secos e inviernos fríos,
-- con heladas de noche. Tabriz, en el noroeste, tiene el invierno más duro, con
-- nieve. Qeshm, en el golfo Pérsico, es calurosa y húmeda casi todo el año.
--
