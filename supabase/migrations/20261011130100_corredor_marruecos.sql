-- Marruecos, con Marrakech como ciudad base: es por donde entra y donde pasa
-- más días casi todo el que viaja, como Dubái en Emiratos. Precios en dírhams,
-- sin centavos: el dírham vale menos de medio dólar.
--
-- Cuatro climas en un país. La costa atlántica —Casablanca, Essaouira— es suave
-- todo el año. Tánger y Chefchaouen, en el norte, tienen inviernos lluviosos.
-- Marrakech y Fez son secas, con veranos de casi cuarenta grados e inviernos
-- frescos. El Alto Atlas es montaña de verdad: en Imlil, a casi 1.800 metros,
-- las noches de enero bajan de cero. Y Merzouga, en las dunas del Sahara, pasa
-- de los cuarenta en verano y tiene noches frías en invierno.
--
-- Las ciudades son las de los viajes habituales. Ninguna está en el Sahara
-- Occidental, que es un territorio en disputa (spec, 15.2).
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Imlil (Alto Atlas) en enero: -1,5 / 10,4 → frio + fresco → abrigo, cero playa
--   Merzouga (Erg Chebbi) en julio: 26,2 / 41,8 → calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000009000 a 9008, la base es 9000.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

