-- Liberia, con Monrovia como ciudad base: es la capital y por donde entra casi
-- todo el que viaja.
--
-- Precios en DÓLARES, con centavos, aunque la moneda sea el dólar liberiano. Es
-- el caso de Camboya: los dos circulan juntos, y hoteles, restaurantes y casi
-- todo lo que paga un viajero se cobra en dólares estadounidenses. El corredor
-- sigue en dólares liberianos, que es lo que la guía explica.
--
-- Uno de los lugares más lluviosos de África: Monrovia recibe varias veces la
-- lluvia de Buenos Aires, casi toda de mayo a octubre. La temporada seca, de
-- noviembre a abril, es calurosa y húmeda, con el harmattan en enero. Tierra
-- adentro, en Kpatawee y Sapo, llueve un poco menos y hace algo más de
-- calor.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Cascada de Kpatawee (Bong) en enero: 20,6 / 32 → templado + calido → nunca abrigo, playa
--   Cascada de Kpatawee (Bong) en febrero: 21,2 / 33 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000b800 a b808, la base es b800.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

