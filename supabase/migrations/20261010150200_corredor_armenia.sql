-- Armenia, con Ereván como ciudad base. Precios en drams, sin centavos: un
-- dólar son varios cientos de drams.
--
-- Un país de montaña: casi todo está arriba de los mil metros. Ereván y la
-- llanura del Ararat tienen veranos muy calurosos y secos e inviernos fríos,
-- con nieve algunos días. Más arriba el invierno es largo: Guiumri es de las
-- ciudades más frías del país, y en los inviernos duros el lago Seván, a casi
-- dos mil metros, se congela en las orillas. Tsaghkadzor es la estación de esquí.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Guiumri en enero: -15,4 / -3 → frio → abrigo, cero playa
--   Khor Virap en julio: 19,4 / 34,4 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000006300 a 6308, la base es 6300.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

