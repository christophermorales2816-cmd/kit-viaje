-- Togo, con Lomé como ciudad base: es la capital y por donde entra casi todo
-- el que viaja. Precios en francos CFA de África Occidental, sin centavos, la
-- misma moneda que Senegal y Benín.
--
-- Las ciudades del planificador son la costa, las colinas de Kpalimé y el
-- centro, hasta Kara. Ninguna está al norte de Kandé ni cerca de la frontera
-- con Burkina Faso, adonde las recomendaciones de viaje piden no ir; por eso
-- no está Koutammakou, la tierra de los batammariba. La guía lo dice como dato
-- de entrada.
--
-- Calor húmedo todo el año en la costa, con dos temporadas de lluvia: de abril
-- a junio, y en septiembre y octubre. En Lomé, que queda en el corredor seco de
-- la costa, llueve poco. Las colinas de Kpalimé y el monte Agou son más
-- lluviosas y algo más frescas. Hacia el norte, en Sokodé y Kara, hay una sola
-- temporada de lluvias, de mayo a octubre, y un invierno seco con el harmattan.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Monte Agou en diciembre: 17,2 / 28,2 → fresco + templado + calido → capas, playa
--   Kara en febrero: 22 / 36,6 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000b600 a b608, la base es b600.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

