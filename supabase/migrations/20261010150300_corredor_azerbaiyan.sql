--
-- Bakú, sobre el Caspio, tiene veranos calurosos e inviernos templados y es
-- famosa por el viento. Gobustán, al sur, es semidesierto. Al norte, en las
-- laderas del Gran Cáucaso, Sheki, Gabala, Quba y Lahij son frescos, y
-- Shahdag, la estación de esquí, tiene nieve en invierno. Lankaran, en el sur,
-- es subtropical: té, bosques húmedos y lluvia en otoño e invierno.
--
