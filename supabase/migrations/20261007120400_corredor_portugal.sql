-- Portugal, con Lisboa como ciudad base.
--
-- El Atlántico suaviza todo: Lisboa casi nunca baja de ocho grados ni pasa los
-- treinta, y llueve en invierno, no en verano. El interior es más extremo —el
-- valle del Duero y el Alentejo superan los treinta y tres en julio—, y Madeira y
-- Azores juegan su propio partido en medio del océano.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Valle del Duero en enero: 2,6 / 11,8 → frio + fresco → abrigo, cero playa
--   Valle del Duero en julio: 16,2 / 33,4 → fresco + templado + calido → capas, playa
--
