-- India, con Nueva Delhi como ciudad base. Precios en rupias, sin centavos.
--
-- Tres estaciones en casi todo el país: el invierno seco de noviembre a febrero,
-- templado de día y con noches frías en el norte; el calor fuerte de marzo a
-- junio, que en Delhi, Agra o Benarés pasa los cuarenta grados; y el monzón de
-- junio a septiembre, que en Bombay y Goa llueve casi todos los días. Leh, a
-- más de tres mil metros en Ladakh, es otro mundo: inviernos muy por debajo de
-- cero y veranos secos y templados.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Leh (Ladakh) en enero: -14,4 / -2,6 → frio → abrigo, cero playa
--   Agra en mayo: 26,8 / 42,2 → calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000005500 a 5508, la base es 5500.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

