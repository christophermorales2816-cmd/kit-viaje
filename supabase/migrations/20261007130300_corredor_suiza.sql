-- Suiza, con Zúrich como ciudad base. Precios en francos suizos.
--
-- La base no es la capital, igual que Antigua en Guatemala: Berna es la capital,
-- pero el aeropuerto con más vuelos y la ciudad más grande es Zúrich, y ahí
-- empieza casi cualquier viaje. El clima lo decide la altura más que el mes: las
-- ciudades del llano tienen inviernos cerca de cero y veranos templados; Zermatt y
-- St. Moritz, entre 1.600 y 1.800 metros, pasan buena parte del invierno bajo
-- cero; y el Tesino, al sur de los Alpes, es lo más templado del país.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   St. Moritz y la Engadina en enero: -14,6 / -1,8 → frio → abrigo, cero playa
--   Lugano y el Tesino en julio: 16,8 / 27,6 → fresco + templado + calido → capas, playa
--
-- IDS FIJOS: destinos 00000000-…-000000002800 a 2808, la base es 2800.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

