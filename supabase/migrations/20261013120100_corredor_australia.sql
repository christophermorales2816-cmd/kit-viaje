-- Australia, con Sídney como ciudad base: es la ciudad más grande y por
-- donde entra casi todo el que viaja; Canberra, la capital, queda a tres horas.
-- Precios en dólares australianos, con centavos: valen más de medio dólar.
--
-- Las ciudades del planificador van de la costa este —Sídney, Brisbane, las
-- Whitsunday y Cairns, frente a la Gran Barrera— al centro rojo de Uluru, y de
-- Melbourne, Adelaida y Hobart, en el sur, a Perth, del otro lado del país.
--
-- Hemisferio sur: el verano va de diciembre a febrero. El sur tiene cuatro
-- estaciones, con inviernos frescos y noches frías en Hobart; el norte
-- tropical, una temporada de lluvias de diciembre a marzo, y el centro, días de
-- calor seco y noches de helada en invierno.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Uluru (Uluṟu-Kata Tjuṯa) en julio: 3,6 / 19,6 → frio + fresco + templado → abrigo, cero playa
--   Uluru (Uluṟu-Kata Tjuṯa) en enero: 21,6 / 37,8 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000c000 a c008, la base es c000.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

