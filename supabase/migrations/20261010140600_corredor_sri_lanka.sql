-- Sri Lanka, con Colombo como ciudad base. Precios en rupias de Sri Lanka, sin centavos.
--
-- Calor todo el año en la costa, y dos monzones. El del sudoeste, de mayo a
-- septiembre, moja la costa oeste y sur (Colombo, Galle, Mirissa); el del
-- noreste, de octubre a enero, la costa este y el norte (Trincomalee, Arugam
-- Bay). Por eso siempre hay una costa seca. Las montañas del centro —Kandy, Ella,
-- Nuwara Eliya— son más frescas; Nuwara Eliya, a casi dos mil metros, tiene
-- noches frías en enero y febrero.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Nuwara Eliya en febrero: 9,4 / 21,4 → frio + fresco + templado → abrigo, cero playa
--   Trincomalee en junio: 26,6 / 35 → calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000006100 a 6108, la base es 6100.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

