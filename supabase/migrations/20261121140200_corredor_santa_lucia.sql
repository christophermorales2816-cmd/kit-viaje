-- Santa Lucía, con Rodney Bay como ciudad base: es donde duerme la mayoría
-- de los viajeros, aunque casi todos los vuelos internacionales llegan a
-- Hewanorra, en el extremo sur. Precios en dólares del Caribe Oriental,
-- enteros: valen menos de medio dólar, por paridad fija de 2,70.
--
-- Calor parejo en la costa y una selva de montaña en el centro, más fresca y
-- lluviosa. El traslado al aeropuerto de Vieux Fort, que está al lado de la
-- pista, se corrige al final.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   La selva del centro en febrero: 19,9 / 25,8 → templado + calido → nunca abrigo, playa
--   Soufrière y los Pitons en septiembre: 24,5 / 31,3 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000e700 a e708, la base es e700.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

