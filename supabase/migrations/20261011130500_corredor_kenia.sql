-- Kenia, con Nairobi como ciudad base. Precios en chelines kenianos, sin
-- centavos: un dólar son más de cien chelines.
--
-- Está sobre el ecuador, así que no hay invierno ni verano: hay dos temporadas de
-- lluvia, las largas de marzo a mayo y las cortas de octubre a diciembre. Lo que
-- cambia la valija es la altura. Nairobi, a 1.700 metros, y los lagos del Valle
-- del Rift tienen días templados y noches frescas todo el año; en Nanyuki, al pie
-- del monte Kenia, las noches de julio bajan de diez grados. La costa —Mombasa,
-- Diani, Watamu— es calurosa y húmeda los doce meses.
--
-- Las ciudades son las de los viajes habituales. Ninguna está en los condados de
-- la frontera con Somalia ni en Lamu, que las recomendaciones de viaje
-- desaconsejan o restringen.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Nanyuki (monte Kenia) en febrero: 7,4 / 26,4 → frio + fresco + templado + calido → abrigo, playa
--   Mombasa en marzo: 24,6 / 32,4 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000009400 a 9408, la base es 9400.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

