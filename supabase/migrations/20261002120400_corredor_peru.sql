-- Perú, con Lima como ciudad base.
--
-- Tres países en uno: la costa desértica, donde casi no llueve pero el invierno
-- es gris y húmedo; los Andes, donde la altura manda igual que en Bolivia; y la
-- Amazonía, caliente y lluviosa todo el año. Lima en agosto y Cusco en agosto
-- piden valijas distintas aunque estén a una hora de vuelo.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Puno y el Titicaca en julio: -5,2 / 14,2 → frio + fresco → abrigo, cero playa
--   Iquitos en septiembre: 20,8 / 32,2 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000001300 a 1308, la base es 1300.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

