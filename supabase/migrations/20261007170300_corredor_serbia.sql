-- treinta grados. Zlatibor y Kopaonik son los rincones frescos del verano y los
-- de nieve en invierno.
--
-- En Belgrado el transporte público urbano es gratis desde 2025, y en el resto
-- de las ciudades no. Por eso la base pasa a cero al final, después de que las
-- otras ocho tomaron su precio: es la única excepción de la migración.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
