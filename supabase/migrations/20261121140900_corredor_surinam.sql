-- Surinam, con Paramaribo como ciudad base. Precios en dólares surinameses,
-- enteros: la unidad vale unos tres centavos de dólar.
--
-- Calor húmedo todo el año, con dos épocas secas: la larga, de agosto a
-- noviembre, y la corta, de febrero a abril. Brownsberg, sobre una meseta de
-- unos quinientos metros, es lo más fresco. Los lodges del interior venden
-- paquetes con comidas y traslados, y sus factores lo reflejan.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Brownsberg en enero: 19,3 / 27,5 → templado + calido → nunca abrigo, playa
--   Alto río Surinam en octubre: 22,5 / 34 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000ee00 a ee08, la base es ee00.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

