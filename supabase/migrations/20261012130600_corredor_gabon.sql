-- Gabón, con Libreville como ciudad base: es la capital y por donde entra casi
-- todo el que viaja. Precios en francos CFA de África Central, sin centavos, la
-- misma moneda que Camerún y Chad.
--
-- Casi todo el país es selva, y una parte grande es parque nacional. Las
-- ciudades del planificador son la capital y su costa, Lambaréné, Port-Gentil,
-- Franceville y los parques de la Lopé, Loango e Ivindo.
--
-- Sobre el ecuador: calor húmedo todo el año, con una temporada seca, más
-- fresca y nublada, de junio a agosto, y lluvias fuertes de septiembre a mayo,
-- con una pausa corta en enero. En Loango, el mar modera el calor; en Ivindo,
-- en el noreste, llueve en dos temporadas.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Franceville (mesetas Batéké) en julio: 18 / 28 → fresco + templado + calido → capas, playa
--   Parque Nacional de la Lopé en marzo: 21,8 / 32 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000b300 a b308, la base es b300.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

