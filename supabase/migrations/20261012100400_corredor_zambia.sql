-- Zambia, con Livingstone como ciudad base: es el lado zambiano de las
-- Cataratas Victoria y por donde entra casi todo el que viaja. Precios en kwachas,
-- sin centavos.
--
-- Hemisferio sur, con tres estaciones: lluvias de noviembre a marzo, un invierno
-- seco y templado de mayo a agosto, con noches frías en la meseta, y un final de
-- temporada seca muy caluroso, en septiembre y octubre, cuando los valles del
-- Luangwa y del Zambeze pasan los treinta y cinco grados. Es también la mejor
-- época para los safaris.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Parque Nacional Kafue en julio: 6 / 25 → frio + fresco + templado → abrigo, cero playa
--   Lower Zambezi en octubre: 22 / 38 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000009900 a 9908, la base es 9900.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

