-- Santo Tomé y Príncipe, con la ciudad de Santo Tomé como base: es la capital
-- y la del único aeropuerto internacional. Precios en dobras, sin centavos: la
-- dobra está atada al euro, que se acepta en hoteles y en muchos comercios.
--
-- Dos islas sobre el ecuador, con calor húmedo todo el año y una sola temporada
-- seca, la gravana, de junio a septiembre. El norte de Santo Tomé, alrededor de
-- la capital y de la Lagoa Azul, es lo más seco; el sur y las laderas del
-- interior reciben muchísima lluvia. En la montaña, en Bom Sucesso, a más de mil
-- metros, las noches rondan los catorce grados.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Bom Sucesso (Parque Obô) en julio: 14,2 / 20 → fresco + templado → capas, cero playa
--   Lagoa Azul (norte) en marzo: 23,1 / 31,3 → templado + calido → nunca abrigo, playa
--
