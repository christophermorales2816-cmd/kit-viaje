-- Paraguay, con Asunción como ciudad base.
--
-- El calor es el dato: de octubre a marzo la máxima pasa los 30 grados casi todos
-- los días, y en el Chaco más. El invierno es corto y templado de día, con alguna
-- madrugada fresca. Es el país más barato del Cono Sur, y los precios en
-- guaraníes tienen muchos ceros: por eso formatMoney no les pone centavos.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Trinidad y Jesús en julio: 9,4 / 19,6 → frio + fresco + templado → abrigo, cero playa
--   Filadelfia en enero: 23,4 / 35,4 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000001200 a 1208, la base es 1200.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

