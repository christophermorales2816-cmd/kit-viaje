-- frescos que rara vez pasan los veintitrés grados, viento casi todos los días y
-- lluvia repartida en todo el año. Las diferencias entre ciudades son chicas; el
-- interior de Jutlandia es algo más frío. La corona se carga sin centavos.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
