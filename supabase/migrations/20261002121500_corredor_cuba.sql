-- Cuba, con La Habana como ciudad base. Precios en DÓLARES.
--
-- Igual que Venezuela: el país tiene moneda propia, el peso cubano, y una
-- cotización oficial muy lejos de la que se consigue en la calle, pero los
-- precios del planificador se cargan en dólares porque es como se cobra en casas
-- particulares y paladares, y porque en pesos quedarían viejos en semanas. El
-- clima es tropical parejo; lo que cambia es la temporada de huracanes, de junio
-- a noviembre.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Viñales en enero: 16 / 26,6 → fresco + templado + calido → capas, playa
--   Santiago de Cuba en agosto: 24,6 / 33,4 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000001e00 a 1e08, la base es 1e00.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

