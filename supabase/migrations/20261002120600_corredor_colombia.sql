-- Colombia, con Bogotá como ciudad base.
--
-- Los pisos térmicos: Bogotá, a 2.600 metros, es fresca los doce meses y pide
-- campera de noche; Cartagena, al nivel del mar, es Caribe caliente todo el año.
-- Las estaciones no existen. Lo que hay son temporadas de lluvia, y en los Andes
-- son dos por año.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Bogotá en enero: 6,6 / 19,4 → frio + fresco + templado → abrigo, cero playa
--   Santa Marta y el Tayrona en julio: 25 / 33 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000001500 a 1508, la base es 1500.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

