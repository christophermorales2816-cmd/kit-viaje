--
-- Desierto y llanura de los dos ríos, con uno de los veranos más calurosos del
-- mundo: en Bagdad y Basora las máximas pasan los cuarenta y cinco grados en
-- julio y agosto. Los inviernos son templados y cortos, con lluvia. El
-- Kurdistán, en el norte, con Erbil y Sulaimaniya, es más alto y más fresco,
