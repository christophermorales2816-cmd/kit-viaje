--
-- Dos estaciones. De noviembre a junio es seco: Dakar y la costa son templadas,
-- con brisa del Atlántico, y el interior es caluroso. De julio a octubre llueve,
-- sobre todo en agosto y septiembre, y el calor es húmedo; en el delta del Sine
-- Saloum, agosto es de los meses más lluviosos.
--
-- Las ciudades son las de los viajes habituales, entre Saint-Louis y la Petite
-- Côte. Ninguna está en Casamance ni en el este, cerca de la frontera con Malí,
-- donde las recomendaciones de viaje piden más precaución.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
