-- Nigeria, con Lagos como ciudad base: es la ciudad más grande y por donde
-- entra casi todo el que viaja; Abuja, la capital, se visita desde ahí o en un
-- vuelo interno. Precios en nairas, sin centavos.
--
-- Entra con aviso (spec, 15.8): la guía manda a revisar la recomendación de
-- viaje del propio país antes de reservar. Las ciudades del planificador son
-- las del suroeste, Benin City, Abuja y Calabar; ninguna está en el norte ni en
-- el delta del Níger.
--
-- Calor húmedo todo el año en el sur, con dos temporadas de lluvia, de abril
-- a julio y de septiembre a octubre, y una pausa en agosto. Abuja, en el
-- centro, tiene una sola temporada de lluvias, de mayo a octubre, y un invierno
-- seco con el harmattan. La meseta de Obudu, a más de mil quinientos metros, es
-- lo más fresco del país.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Meseta de Obudu en enero: 13 / 24 → fresco + templado → capas, cero playa
--   Abuja en marzo: 23,4 / 36 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000a600 a a608, la base es a600.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

