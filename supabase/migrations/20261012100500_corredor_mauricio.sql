-- Mauricio, con Grand Baie como ciudad base: es el centro turístico del norte
-- y donde se aloja buena parte de los que viajan; Port Louis, la capital, se
-- visita en el día. Precios en rupias mauricianas, sin centavos.
--
-- Hemisferio sur y trópico: calor húmedo de noviembre a abril, con la temporada
-- de ciclones de enero a marzo, e inviernos templados y ventosos de junio a
-- septiembre. La isla cambia en pocos kilómetros: el oeste, en Flic en Flac y Le
-- Morne, es lo más seco y soleado; el este y el sur reciben los alisios y más
-- lluvia; y la meseta central, en Curepipe, es fresca y lluviosa casi todo el
-- año. Rodrigues, a casi seiscientos kilómetros, es otra isla, más tranquila y
-- seca.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Curepipe (meseta central) en agosto: 13,9 / 19,8 → fresco + templado → capas, cero playa
--   Flic en Flac en febrero: 24 / 31,4 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000009a00 a 9a08, la base es 9a00.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

