-- Tuvalu, con Funafuti como ciudad base: es la capital y el único
-- aeropuerto del país. Precios en dólares australianos, con centavos: es la
-- moneda de Tuvalu, que acuña además sus propias monedas.
--
-- Las ciudades del planificador son Funafuti, su área de conservación y las
-- otras islas del país, a las que se llega en el barco del gobierno, que sale
-- pocas veces por mes: Nukufetau, Vaitupu, Nui, Nanumea, Niutao, Nanumanga y
-- Nukulaelae.
--
-- Calor húmedo y parejo todo el año, sin estaciones de temperatura: lo que
-- cambia es la lluvia, más fuerte de noviembre a marzo, la temporada de
-- ciclones. Ningún punto del país está a más de cinco metros sobre el mar.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Funafuti en julio: 25,4 / 31,2 → calido → nunca abrigo, playa
--   Nui en abril: 25,6 / 31,8 → calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000cb00 a cb08, la base es cb00.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

