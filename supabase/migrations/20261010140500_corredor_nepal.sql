-- Nepal, con Katmandú como ciudad base. Precios en rupias nepalesas, sin centavos.
--
-- La altura manda más que el mes. Katmandú, a mil cuatrocientos metros, tiene
-- inviernos secos con noches frías y un monzón de junio a septiembre que llueve
-- casi todos los días. Chitwan y Lumbini, en la llanura del sur, son calurosos
-- antes del monzón. Namche Bazar, a casi tres mil quinientos metros en la ruta
-- del Everest, pasa el invierno bajo cero; Jomsom, detrás de los Annapurna,
-- queda a la sombra del monzón y casi no llueve.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Namche Bazar (Everest) en enero: -8,4 / 6,6 → frio → abrigo, cero playa
--   Lumbini en mayo: 23,8 / 36,6 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000006000 a 6008, la base es 6000.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

