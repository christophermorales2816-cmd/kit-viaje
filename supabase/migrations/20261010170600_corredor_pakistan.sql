-- centavos: un dólar son varios cientos de rupias.
--
-- Entra con aviso (spec, 14.11): la guía manda a revisar la recomendación de
-- viaje del propio país antes de reservar. Las ciudades del planificador son la
-- capital, Lahore, Karachi y el norte de montaña; ninguna está en Baluchistán
-- ni en las zonas tribales.
--
-- Del mar de Arabia a las montañas más altas del mundo. Lahore y la llanura
-- tienen veranos de calor extremo, con más de cuarenta grados en junio, y
-- monzón en julio y agosto. Islamabad, al pie de las montañas, es algo más
-- fresca. El norte, con Gilgit, Hunza y Skardu, es montaña seca: veranos
-- templados e inviernos fríos, y Fairy Meadows, a más de tres mil metros, está
-- bajo cero buena parte del año. Karachi, en la costa, es calurosa y húmeda.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Fairy Meadows (Nanga Parbat) en enero: -14 / -2 → frio → abrigo, cero playa
--   Lahore en junio: 27,4 / 40,2 → calido → nunca abrigo, playa
--
