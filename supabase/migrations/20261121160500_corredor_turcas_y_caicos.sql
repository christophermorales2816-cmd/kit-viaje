-- dólares estadounidenses, con centavos: las islas usan el dólar.
--
-- Calor seco y con brisa, de las islas más secas de la región. No hay buses:
-- el transporte del día es el taxi, que cobra por persona, y el de larga
-- distancia, el vuelo o el ferry a otra isla.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
