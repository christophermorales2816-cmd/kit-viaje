-- centavos: el dinar vale más de un dólar, y un falafel cuesta menos de una unidad.
--
-- Más fría de lo que se espera. Amán, Petra y las ciudades de la meseta están
-- entre seiscientos y mil doscientos metros: inviernos fríos y lluviosos, a veces
-- con nieve, y veranos calurosos y secos. El Mar Muerto, a cuatrocientos metros
-- bajo el nivel del mar, y Áqaba, sobre el mar Rojo, tienen inviernos templados y
-- veranos de calor fuerte. Wadi Rum es desierto: días calurosos y noches frías.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
