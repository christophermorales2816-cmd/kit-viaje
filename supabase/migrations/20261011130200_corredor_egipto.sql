-- Egipto, con El Cairo como ciudad base. Precios en libras egipcias, sin
-- centavos: un dólar son decenas de libras.
--
-- Casi no llueve en ningún lado. Lo que cambia es el calor: El Cairo y
-- Alejandría tienen inviernos templados y veranos calurosos; Luxor, Asuán y Abu
-- Simbel, en el sur, pasan los cuarenta grados de mayo a septiembre y tienen
-- noches frescas en enero. Las playas del mar Rojo —Hurghada, Marsa Alam,
-- Sharm el-Sheij— son templadas en invierno y muy calurosas en verano.
--
-- Las ciudades son las de los viajes habituales: el Nilo, el mar Rojo y Sharm
-- el-Sheij, al que se llega en avión. Ninguna está en el norte del Sinaí, en el
-- resto de la península, en el desierto occidental ni sobre las fronteras, que
-- las recomendaciones de viaje desaconsejan.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Luxor en enero: 5,8 / 23 → frio + fresco + templado → abrigo, cero playa
--   Abu Simbel en junio: 25,6 / 41,8 → calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000009100 a 9108, la base es 9100.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

