-- Calor todo el año, y tres estaciones que se cuentan por la lluvia: la fresca y
-- seca de noviembre a febrero, la calurosa de marzo a mayo y la de lluvias de
-- junio a octubre. Ko Samui, en el golfo, es la excepción: su temporada de
-- lluvias va de octubre a diciembre. En el norte —Chiang Mai, Chiang Rai, Pai—
-- las noches de diciembre y enero son frescas.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
