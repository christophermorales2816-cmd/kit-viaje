-- Tercer corredor: Bolivia, con La Paz como ciudad base.
--
-- Misma estructura que Argentina y Brasil, sin inventar nada nuevo: destinos con
-- slug e is_base, doce meses de clima por ciudad, precios de la base y el resto
-- derivado con un factor. packing_catalog sigue sin tocarse — es global.
--
-- LO QUE HACE DISTINTO A ESTE CORREDOR: en Argentina y Brasil la valija la
-- decide la estación; acá la decide la ALTURA. La Paz está a 3.600 m y tiene
-- prácticamente la misma temperatura los doce meses (unos 14 de máxima, cerca de
-- cero de mínima), mientras que Rurrenabaque, a 200 m y a un vuelo corto, no
-- baja de 17. Contra los umbrales sembrados (frio ≤10, fresco ≤18, templado ≤25,
-- calido sin tope) eso da:
--
--   La Paz, cualquier mes   ~0 / ~14   → frio + fresco       → capas y abrigo
--   Potosí en junio         −4,8 / 14,6 → frio + fresco      → abrigo de verdad
--   Rurrenabaque en enero   22,4 / 31,0 → templado + cálido  → nunca abrigo
--
-- Por eso el mismo viaje de dos semanas puede pedir campera y ojotas: no es un
-- error de carga, es Bolivia.
--
-- IDS FIJOS, en rangos que no chocan con los corredores anteriores:
--
--   00000000-…-00b0        destino La Paz (base)
--   00000000-…-0000000d01..d08  las otras ocho ciudades
--   b2000000-…-00NN        products de La Paz

