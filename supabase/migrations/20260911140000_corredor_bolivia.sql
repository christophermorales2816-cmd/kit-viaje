-- ===========================================================================
-- 4. Las otras ocho ciudades, derivadas con un factor
-- ===========================================================================
--
-- Mismo mecanismo que las ciudades de Argentina y Brasil. Uyuni y Rurrenabaque
-- salen caras porque casi todo se compra como excursión; Potosí y Sucre son más
-- baratas que la sede de gobierno.

insert into products
  (id, destination_id, category, name, base_price, currency,
   base_qty, scales_with_days, days_per_unit, max_qty)
select
  md5(ciudad.id::text || p.name)::uuid,
  ciudad.id, p.category, p.name, round(p.base_price * ciudad.factor), p.currency,
  p.base_qty, p.scales_with_days, p.days_per_unit, p.max_qty
from (values
  ('00000000-0000-4000-8000-000000000d01'::uuid, 1.25),  -- Salar de Uyuni
  ('00000000-0000-4000-8000-000000000d02'::uuid, 1.05),  -- Copacabana
  ('00000000-0000-4000-8000-000000000d03'::uuid, 0.90),  -- Potosí
  ('00000000-0000-4000-8000-000000000d04'::uuid, 0.95),  -- Sucre
  ('00000000-0000-4000-8000-000000000d05'::uuid, 0.95),  -- Cochabamba
  ('00000000-0000-4000-8000-000000000d06'::uuid, 1.00),  -- Tarija
  ('00000000-0000-4000-8000-000000000d07'::uuid, 1.30),  -- Santa Cruz de la Sierra
  ('00000000-0000-4000-8000-000000000d08'::uuid, 1.20)   -- Rurrenabaque
) as ciudad(id, factor)
join products p on p.destination_id = '00000000-0000-4000-8000-0000000000b0'
on conflict (id) do nothing;
