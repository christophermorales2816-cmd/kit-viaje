-- Arabia Saudita, con Riad como ciudad base. Precios en riyales saudíes, sin
-- centavos: el riyal vale un cuarto de dólar, como el zloty.
--
-- Desierto casi todo el país. Riad, en el centro, tiene inviernos templados y
-- veranos de calor extremo y seco, con máximas de más de cuarenta grados de
-- mayo a septiembre. Yeda y la costa del mar Rojo son calurosas y húmedas todo
-- el año. Abha y Taif, en las montañas del oeste, a dos mil metros, son
-- frescas, y Abha tiene lluvias de verano. AlUla y Hail, en el norte, tienen
-- noches frías en invierno.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Hail en enero: 3,6 / 16,2 → frio + fresco → abrigo, cero playa
--   Oasis de Al Ahsa en julio: 31,6 / 45,4 → calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000006800 a 6808, la base es 6800.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

