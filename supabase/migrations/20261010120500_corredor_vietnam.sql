-- invierno fresco y gris de diciembre a febrero y un verano caluroso y lluvioso;
-- Sapa, en la montaña, puede bajar de los cinco grados en enero. El centro (Hue,
-- Hoi An, Da Nang) llueve sobre todo de septiembre a diciembre. El sur (Ciudad
-- Ho Chi Minh, Phu Quoc) es caluroso todo el año, con lluvias de mayo a
-- noviembre.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
