-- Sierra Leona, con Freetown como ciudad base: es la capital y por donde entra
-- casi todo el que viaja, aunque el aeropuerto esté del otro lado de la bahía,
-- en Lungi. Precios en leones, sin centavos: desde 2022, el leone nuevo, con
-- tres ceros menos.
--
-- Calor húmedo todo el año y una de las temporadas de lluvia más fuertes de
-- África, de mayo a octubre: en julio y agosto llueve casi todos los días. De
-- noviembre a abril es la temporada seca, la de las playas de la península. Las
-- colinas de Freetown, en Tacugama, son algo más frescas; tierra adentro, en
-- Makeni y en el parque de Outamba-Kilimi, la temporada seca es más
-- calurosa.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Parque Nacional Outamba-Kilimi en enero: 19 / 34,4 → templado + calido → nunca abrigo, playa
--   Parque Nacional Outamba-Kilimi en marzo: 21,8 / 36,4 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000b900 a b908, la base es b900.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

