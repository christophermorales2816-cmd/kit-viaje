-- Cuarto corredor de Sudamérica: Chile, con Santiago como ciudad base.
--
-- Lo que define a este país para la valija es la LATITUD. Son 4.300 km de norte
-- a sur: el desierto de altura de Atacama, el clima mediterráneo de Santiago, la
-- lluvia del sur y el viento de la Patagonia. Isla de Pascua, a 3.700 km del
-- continente, juega en otro océano.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   San Pedro de Atacama en julio: -2 / 20 → frio + fresco + templado → abrigo, cero playa
--   Santiago en enero: 13 / 30,8 → fresco + templado + calido → capas, playa
--
