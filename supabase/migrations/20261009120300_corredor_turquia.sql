-- Turquía, con Estambul como ciudad base. Precios en liras turcas, sin centavos.
--
-- La lira tiene inflación alta: estos precios se ponen viejos más rápido que los
-- de cualquier otro país, y la vista muestra su antigüedad. Son órdenes de
-- magnitud para planificar.
--
-- Un país grande con climas distintos: Estambul tiene inviernos fríos y
-- lluviosos y veranos calurosos; la costa del Egeo y el Mediterráneo, veranos
-- largos y secos; Capadocia, en la meseta, inviernos con nieve; y la costa del
-- Mar Negro, con Trabzon, llueve en cualquier mes.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Capadocia en enero: -6 / 3,8 → frio → abrigo, cero playa
--   Pamukkale en julio: 20,6 / 35,2 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000004600 a 4608, la base es 4600.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

