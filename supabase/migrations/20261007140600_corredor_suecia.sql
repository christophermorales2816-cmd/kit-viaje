-- Suecia, con Estocolmo como ciudad base. Precios en coronas suecas.
--
-- El sur —Estocolmo, Gotemburgo, Malmö— tiene inviernos cerca de cero y veranos
-- templados con días larguísimos. Hacia el norte el invierno se endurece: Dalarna
-- y la Costa Alta pasan meses bajo cero, y Kiruna, en Laponia, por encima del
-- círculo polar, tiene máximas bajo cero de noviembre a marzo. La corona se carga
-- sin centavos.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Kiruna y la Laponia en enero: -17 / -9,2 → frio → abrigo, cero playa
--   Kalmar y Öland en julio: 13,8 / 23,4 → fresco + templado → capas, cero playa
--
