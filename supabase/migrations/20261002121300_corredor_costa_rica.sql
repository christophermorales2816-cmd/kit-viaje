-- Costa Rica, con San José como ciudad base.
--
-- Un valle central templado y dos costas que no comparten temporada: el Pacífico
-- tiene una estación seca clara de diciembre a abril, y el Caribe llueve casi
-- todo el año con dos ventanas secas, en marzo y en septiembre-octubre. La
-- estación de lluvias se llama "verde" por algo. Es el país más caro de
-- Centroamérica.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Monteverde en enero: 14,6 / 20,6 → fresco + templado → capas, cero playa
--   Tamarindo en abril: 24,2 / 34,8 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000001c00 a 1c08, la base es 1c00.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

