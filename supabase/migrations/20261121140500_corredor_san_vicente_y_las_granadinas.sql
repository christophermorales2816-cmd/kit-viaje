-- San Vicente y las Granadinas, con Kingstown como ciudad base. Precios en
-- dólares del Caribe Oriental, enteros: valen menos de medio dólar.
--
-- San Vicente es volcánica y lluviosa; La Soufrière se modela en la subida, a
-- unos quinientos metros, más fresca y con nubes. Las Granadinas son más secas.
-- Mustique lleva el factor máximo que acepta el generador (2,5): es una isla
-- privada de lujo, y aun así se queda corto.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   La Soufrière en febrero: 19,4 / 25,5 → templado + calido → nunca abrigo, playa
--   La costa de sotavento en septiembre: 24,4 / 31,2 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000ea00 a ea08, la base es ea00.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

