-- Turkmenistán, con Asjabad como ciudad base. Precios en DÓLARES, no en manats:
-- el manat tiene una cotización oficial y otra en la calle muy lejos entre sí, y
-- al viajero los hoteles y las agencias le cobran en dólares. Mismo criterio
-- que Venezuela y Cuba.
--
-- Desierto continental: el Karakum cubre casi todo el país. Veranos muy
-- calurosos y secos, con más de treinta y cinco grados de junio a agosto, e
-- inviernos fríos, con heladas en todo el país y más duras en el norte, en
-- Konye-Urgench y Dashoguz. La costa del Caspio, en Turkmenbashi y Avaza, es
-- un poco más templada.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Konye-Urgench en enero: -7 / 2,4 → frio → abrigo, cero playa
--   Darvaza (cráter de gas) en julio: 25 / 40 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000006c00 a 6c08, la base es 6c00.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

