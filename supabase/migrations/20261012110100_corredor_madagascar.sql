-- Madagascar, con Antananarivo como ciudad base: es la capital y por donde entra
-- casi todo el que viaja. Precios en la moneda local, el ariary, sin
-- centavos.
--
-- Hemisferio sur y trópico, pero la isla es grande y cambia mucho. Las tierras
-- altas del centro —Antananarivo, Antsirabe— tienen veranos lluviosos e
-- inviernos secos y frescos: en julio, las noches de Antsirabe rondan los seis
-- grados. La selva del este, en Andasibe y Ranomafana, llueve casi todo el año.
-- El oeste y el sur —Morondava, Isalo, Toliara— son secos y calurosos, con
-- lluvias cortas de diciembre a marzo. El norte, en Nosy Be y Diego Suárez, es
-- tropical, con la temporada de ciclones de enero a marzo.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Antsirabe en julio: 6,2 / 18,8 → frio + fresco + templado → abrigo, cero playa
--   Ifaty (Toliara) en febrero: 22,3 / 32,6 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000009e00 a 9e08, la base es 9e00.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

