-- Noruega, con Oslo como ciudad base. Precios en coronas noruegas.
--
-- Un país largo como Chile, pero en el hemisferio norte: Oslo tiene inviernos bajo
-- cero y veranos templados; la costa oeste —Bergen, Stavanger, Ålesund— es más
-- suave y mucho más lluviosa; y el norte, con Tromsø y Lofoten, pasa el invierno
-- cerca o debajo de cero, con noche polar en diciembre y sol de medianoche en
-- junio. La corona se carga sin centavos.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Oslo en enero: -6,8 / -0,6 → frio → abrigo, cero playa
--   Oslo en julio: 12,6 / 22,6 → fresco + templado → capas, cero playa
--
-- IDS FIJOS: destinos 00000000-…-000000003000 a 3008, la base es 3000.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

