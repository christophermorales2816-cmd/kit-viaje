-- Laos, con Luang Prabang como ciudad base. Precios en kips, sin centavos.
--
-- La base es Luang Prabang y no Vientián, como Antigua en Guatemala: es la
-- ciudad por la que se viaja a Laos.
--
-- Tres estaciones: la seca y fresca de noviembre a febrero, la calurosa de marzo
-- a mayo y la de lluvias de mayo a octubre. En las montañas del norte —Phonsavan,
-- en la Llanura de las Jarras, Luang Namtha, Nong Khiaw— las madrugadas de
-- diciembre y enero son frías. Las Cuatro Mil Islas, en el sur, son las más
-- calurosas.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Phonsavan y la Llanura de las Jarras en enero: 6,8 / 23 → frio + fresco + templado → abrigo, cero playa
--   Cuatro Mil Islas (Si Phan Don) en abril: 24,8 / 35,6 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000005b00 a 5b08, la base es 5b00.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

