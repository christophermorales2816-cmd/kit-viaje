-- Sudáfrica, con Ciudad del Cabo como ciudad base: es la capital legislativa
-- —el país tiene tres— y el destino de casi todo el que viaja. Precios en rands,
-- sin centavos.
--
-- Hemisferio sur, y tres climas. El Cabo es mediterráneo: veranos secos y
-- ventosos, inviernos templados y lluviosos, al revés que el resto del país.
-- Johannesburgo y el Drakensberg están en la meseta, con tormentas de verano e
-- inviernos secos de noches frías: en el Drakensberg, julio roza los cero
-- grados. El Kruger y Durban son subtropicales, calurosos y húmedos en verano.
-- El Pequeño Karoo, en Oudtshoorn, es semidesierto: pasa de los treinta en enero
-- y hiela en las noches de julio.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Drakensberg en julio: 0,2 / 16,6 → frio + fresco → abrigo, cero playa
--   Parque Kruger en enero: 20,8 / 32,4 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000009300 a 9308, la base es 9300.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

