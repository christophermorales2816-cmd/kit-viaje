-- viaje del propio país antes de reservar.
--
-- Mediterráneo en la costa y en las montañas, desierto en el sur y en el valle
-- del Jordán. Tel Aviv y Haifa tienen veranos calurosos y húmedos e inviernos
-- templados con lluvia. Jerusalén y Belén, a ochocientos metros, son más
-- frescas, con noches frías en invierno. El mar Muerto, Jericó y Eilat son
-- desierto: calor seco casi todo el año.
--
