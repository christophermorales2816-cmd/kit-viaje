-- Islandia, con Reikiavik como ciudad base. Precios en coronas islandesas.
--
-- El clima es menos frío de lo que el nombre promete y más cambiante de lo que
-- cualquiera espera: la costa sur y Reikiavik tienen inviernos cerca de cero y
-- veranos frescos que casi nunca pasan los quince grados, con viento y lluvia en
-- cualquier mes. El norte y el interior son más fríos: Mývatn pasa el invierno
-- bajo cero. La corona se carga sin centavos.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Lago Mývatn en enero: -9 / -1,6 → frio → abrigo, cero playa
--   Akureyri en julio: 7,8 / 15,2 → frio + fresco → abrigo, cero playa
--
-- IDS FIJOS: destinos 00000000-…-000000003300 a 3308, la base es 3300.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

