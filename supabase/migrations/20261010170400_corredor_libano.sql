-- Entra con aviso (spec, 14.11): la guía manda a revisar la recomendación de
-- viaje del propio país antes de reservar. Ninguna ciudad del planificador
-- está al sur de Sidón ni en el valle de la Bekaa.
--
-- Mediterráneo con montañas altas a pocos kilómetros del mar. Beirut, Biblos y
-- la costa tienen veranos calurosos y húmedos e inviernos templados y
-- lluviosos. Bsharri y los cedros, a casi mil quinientos metros, tienen
-- inviernos fríos con nieve, y Faraya, la estación de esquí, a casi dos mil,
-- está bajo cero de noche de diciembre a marzo.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Faraya en enero: -2,6 / 4,4 → frio → abrigo, cero playa
--   Sidón en agosto: 25,2 / 32 → calido → nunca abrigo, playa
--
