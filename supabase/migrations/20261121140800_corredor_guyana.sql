-- Guyana, con Georgetown como ciudad base. Precios en dólares guyaneses,
-- enteros: la unidad vale medio centavo de dólar.
--
-- Tres climas: la costa, con dos temporadas de lluvias; la selva del interior,
-- con una sola, de mayo a agosto; y la sabana de la Rupununi, más seca y
-- calurosa. Kaieteur, sobre su meseta, es lo más lluvioso. Los lodges del
-- interior venden paquetes con comidas y traslados, y sus factores lo reflejan.
-- Entra con aviso (spec, 22): ninguna ciudad está cerca de la frontera con
-- Venezuela.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Cataratas de Kaieteur en enero: 20,5 / 28,5 → templado + calido → nunca abrigo, playa
--   Karanambu en octubre: 23 / 34,5 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000ed00 a ed08, la base es ed00.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

