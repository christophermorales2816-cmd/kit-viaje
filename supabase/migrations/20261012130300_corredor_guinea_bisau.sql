-- Guinea-Bisáu, con Bisáu como ciudad base: es la capital y por donde entra
-- casi todo el que viaja. Precios en francos CFA de África Occidental, sin
-- centavos, la misma moneda que Senegal y Costa de Marfil.
--
-- Entra con aviso (spec, 15.9): la guía manda a revisar la recomendación de
-- viaje del propio país antes de reservar. Las ciudades del planificador son la
-- capital, el archipiélago de las Bijagós, Bolama, Cacheu, Cantanhez y Bafatá;
-- ninguna está a menos de veinte kilómetros de la frontera con Senegal, así que
-- Varela y São Domingos no están.
--
-- Calor húmedo todo el año, con una temporada de lluvias fuerte, de junio a
-- octubre, y otra seca, de noviembre a mayo, con el harmattan. En las Bijagós,
-- el mar modera el calor; tierra adentro, en Bafatá, abril y mayo pasan los
-- treinta y cinco grados.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Bafatá en enero: 16,4 / 33,6 → fresco + templado + calido → capas, playa
--   Bafatá en abril: 22,4 / 37,8 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000b000 a b008, la base es b000.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

