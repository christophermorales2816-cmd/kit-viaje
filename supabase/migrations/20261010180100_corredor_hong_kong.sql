--
-- Las nueve "ciudades" del planificador son barrios e islas de un territorio
-- chico, como en Singapur. Subtropical: inviernos templados y secos, de
-- noviembre a febrero, y veranos calurosos y muy húmedos, con lluvias fuertes y
-- tifones de junio a septiembre. Victoria Peak, a más de quinientos metros, es
-- un poco más fresco.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Victoria Peak en enero: 12,4 / 16,4 → fresco → capas, cero playa
--   Central y Sheung Wan en julio: 27 / 31,6 → calido → nunca abrigo, playa
--
