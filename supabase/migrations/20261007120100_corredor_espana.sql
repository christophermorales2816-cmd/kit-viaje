-- España, con Madrid como ciudad base. Primer corredor de Europa.
--
-- Hemisferio norte: enero es invierno. Y cuatro climas en un país: la meseta de
-- Madrid, fría en invierno y con un verano seco que pasa los treinta y cinco
-- grados; el Mediterráneo templado; el norte verde y lluvioso; y Canarias, con
-- primavera los doce meses frente a África. Precios en euros, con centavos.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Granada en enero: 0,7 / 12,6 → frio + fresco → abrigo, cero playa
--   Sevilla en julio: 20,3 / 36 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000002000 a 2008, la base es 2000.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

