-- Bután, con Timbu como ciudad base. Precios en ngultrums, sin centavos: el
-- ngultrum está atado a la rupia india, uno a uno.
--
-- Los precios del planificador no incluyen la tasa diaria de desarrollo
-- sostenible que paga cada visitante, ni el paquete con guía y auto que la
-- mayoría contrata: son lo que se gasta por fuera de eso.
--
-- Montaña con monzón. Timbu y Paro, a más de dos mil metros, tienen inviernos
-- secos y soleados con heladas de noche, y veranos templados y lluviosos.
-- Punakha y Wangdue, en valles más bajos, son templados en invierno. Phobjikha,
-- Bumthang y Haa, más arriba, son fríos. El monzón va de junio a septiembre;
-- Phuentsholing, en la frontera con la India, es subtropical y muy lluvioso.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Valle de Phobjikha (Gangtey) en enero: -7,6 / 7,6 → frio → abrigo, cero playa
--   Phuentsholing en agosto: 24 / 31,4 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000006e00 a 6e08, la base es 6e00.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

