-- República Dominicana, con Santo Domingo como ciudad base.
--
-- Caribe todo el año al nivel del mar, sin un mes de abrigo. La excepción está en
-- la Cordillera Central: Constanza, a 1.200 metros, tiene madrugadas de menos de
-- diez grados en invierno, algo que casi nadie espera en el Caribe. La temporada
-- de huracanes va de junio a noviembre.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Constanza en enero: 8,6 / 23 → frio + fresco + templado → abrigo, cero playa
--   Pedernales y Bahía de las Águilas en agosto: 24,4 / 33,6 → templado + calido → nunca abrigo, playa
--
