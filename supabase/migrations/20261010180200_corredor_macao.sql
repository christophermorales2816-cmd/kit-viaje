-- Macao, con el centro histórico como base. Precios en patacas, sin centavos:
-- la pataca vale casi lo mismo que el dólar de Hong Kong, que también circula.
--
-- Las nueve "ciudades" del planificador son barrios de un territorio chiquito,
-- como en Catar o Singapur: la península, Taipa, Cotai y Coloane comparten el
-- clima. Subtropical: inviernos templados y secos, y veranos calurosos y muy
-- húmedos, con lluvias fuertes y tifones de junio a septiembre.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Centro histórico (Largo do Senado) en enero: 12,6 / 18,4 → fresco + templado → capas, cero playa
--   Centro histórico (Largo do Senado) en julio: 26,4 / 31,6 → calido → nunca abrigo, playa
--
