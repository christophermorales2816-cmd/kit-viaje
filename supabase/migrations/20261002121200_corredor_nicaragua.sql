--
-- Lagos y volcanes en el Pacífico, caluroso todo el año y más todavía en abril,
-- antes de las lluvias. Las montañas del norte, Matagalpa y Estelí, son lo único
-- templado. La costa caribe y las Corn Islands son otra historia: llueve mucho
-- más y la temporada seca es corta.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Estelí en enero: 15,8 / 27 → fresco + templado + calido → capas, playa
--   León en abril: 24 / 36 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000001b00 a 1b08, la base es 1b00.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

