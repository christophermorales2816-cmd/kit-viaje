-- Maldivas, con Malé como ciudad base. Precios en DÓLARES, no en rufiyaas:
-- como en Camboya, al viajero se le cobra en dólares —los resorts, las
-- lanchas, el buceo— aunque la moneda del país sea otra.
--
-- Los precios de la base son de isla local y casas de huéspedes. Los atolones
-- de resorts llevan el factor más alto que admite el planificador, y aun así
-- un resort puede costar varias veces más: el número es para planificar una
-- isla local con excursiones, no una villa sobre el agua.
--
-- Ecuatorial: calor parejo todo el año, alrededor de treinta grados, y el agua
-- igual. De diciembre a abril es la temporada seca del monzón del noreste; de
-- mayo a noviembre, la del sudoeste, con más lluvia y viento. Addu y
-- Fuvahmulah, en el sur, sobre el ecuador, tienen lluvia todo el año.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Atolón Addu en noviembre: 25 / 30,2 → templado + calido → nunca abrigo, playa
--   Malé en abril: 27,4 / 31,8 → calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000006d00 a 6d08, la base es 6d00.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

