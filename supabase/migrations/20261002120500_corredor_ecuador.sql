-- Ecuador, con Quito como ciudad base. Primer país dolarizado.
--
-- La línea del ecuador cruza el país, así que no hay verano ni invierno: Quito
-- tiene casi la misma temperatura los doce meses, y lo que cambia la valija es la
-- altura y la región — Sierra, Costa, Amazonía y Galápagos. Los precios van en
-- dólares, con centavos, y las ciudades derivadas se redondean al centavo y no a
-- la unidad.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Otavalo en agosto: 7 / 21 → frio + fresco + templado → abrigo, cero playa
--   Guayaquil en marzo: 23,2 / 31,6 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000001400 a 1408, la base es 1400.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

