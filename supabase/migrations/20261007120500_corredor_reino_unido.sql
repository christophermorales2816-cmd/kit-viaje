-- Reino Unido, con Londres como ciudad base. Precios en libras.
--
-- Un clima sin extremos y sin garantías: Londres casi nunca baja de cero ni pasa
-- los veinticinco, pero la lluvia aparece cualquier día del año. Escocia es más
-- fresca y más lluviosa. El verano no es un verano de playa, y por eso el motor
-- casi nunca propone ropa de calor.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Tierras Altas en enero: 0,8 / 6,8 → frio → abrigo, cero playa
--   Londres en julio: 13,8 / 23,6 → fresco + templado → capas, cero playa
--
