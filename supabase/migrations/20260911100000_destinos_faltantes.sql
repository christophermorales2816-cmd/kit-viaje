-- Precios derivados de la ciudad base con un factor, igual que el resto (11.3).
-- Noronha lleva 1,80 y no es exageración: tiene cupo de visitantes y tasa
-- ambiental diaria, y es el destino más caro de los dieciocho.

insert into products
  (id, destination_id, category, name, base_price, currency,
   base_qty, scales_with_days, days_per_unit, max_qty)
select
  md5(ciudad.id::text || p.name)::uuid,
  ciudad.id, p.category, p.name, round(p.base_price * ciudad.factor), p.currency,
  p.base_qty, p.scales_with_days, p.days_per_unit, p.max_qty
from (values
  ('00000000-0000-4000-8000-000000000a06'::uuid, '00000000-0000-4000-8000-0000000000ba'::uuid, 1.30),  -- El Calafate
  ('00000000-0000-4000-8000-000000000a07'::uuid, '00000000-0000-4000-8000-0000000000ba'::uuid, 1.30),  -- El Chaltén
  ('00000000-0000-4000-8000-000000000a08'::uuid, '00000000-0000-4000-8000-0000000000ba'::uuid, 1.05),  -- Puerto Madryn
  ('00000000-0000-4000-8000-000000000c05'::uuid, '00000000-0000-4000-8000-0000000000b2'::uuid, 0.85),  -- Recife
