  ('00000000-0000-4000-8000-000000000c08'::uuid, '00000000-0000-4000-8000-0000000000b2'::uuid, 1.20)   -- Pantanal
) as ciudad(id, base_id, factor)
join products p on p.destination_id = ciudad.base_id
