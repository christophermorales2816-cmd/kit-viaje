-- lago Khövsgöl, en el norte, baja de treinta. Los veranos son cortos y
-- templados, con lluvia en julio y agosto. El Gobi, en el sur, es desierto:
-- calor de día en verano, heladas de noche en invierno y casi nada de lluvia.
