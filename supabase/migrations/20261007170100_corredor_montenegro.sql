-- Montenegro, con Kotor como ciudad base. Precios en euros, con centavos:
-- Montenegro usa el euro aunque no es parte de la zona euro.
--
-- La costa es mediterránea, con veranos largos y secos e inviernos suaves, y la
-- bahía de Kotor, encajonada entre montañas, es de los lugares más lluviosos de
-- Europa entre noviembre y enero. El interior sube rápido: Cetinje y el Lovćen
-- son frescos, y Durmitor, a más de 1.400 metros, tiene inviernos de nieve.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Durmitor y el cañón del Tara en enero: -8,6 / 0,4 → frio → abrigo, cero playa
--   Lago de Skadar en agosto: 20 / 33,2 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000003e00 a 3e08, la base es 3e00.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

