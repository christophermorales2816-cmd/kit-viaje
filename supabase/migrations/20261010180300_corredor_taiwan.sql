-- metros en el medio. Taipéi tiene inviernos templados y grises, con lluvia
-- fina, y veranos muy calurosos y húmedos, con tifones de julio a septiembre.
-- El sur, con Tainan, Kaohsiung y Kenting, es seco en invierno y llueve en
