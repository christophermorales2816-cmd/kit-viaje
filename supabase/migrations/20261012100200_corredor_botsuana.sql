-- Botsuana, con Maun como ciudad base: es la puerta del delta del Okavango y
-- por donde entra casi todo el que viaja, como Arusha en Tanzania. Precios en
-- pulas, sin centavos.
--
-- Hemisferio sur, con veranos calurosos y lluvias de noviembre a marzo, e
-- inviernos secos de días templados y noches frías: en el Kalahari, las noches
-- de julio rondan los dos grados. El delta se inunda al revés de la lluvia: el
-- agua llega desde Angola y lo llena en plena temporada seca, de junio a agosto.
-- Los parques y concesiones del norte cobran tarifas altas a propósito: el país
-- eligió pocos visitantes que paguen mucho.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Kalahari Central en julio: 2 / 22,5 → frio + fresco + templado → abrigo, cero playa
--   Maun en octubre: 17,5 / 35 → fresco + templado + calido → capas, playa
--
-- IDS FIJOS: destinos 00000000-…-000000009700 a 9708, la base es 9700.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

