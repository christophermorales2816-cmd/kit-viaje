-- Polinesia Francesa, con Papeete como ciudad base: es la capital, en Tahití,
-- y por donde entra todo el que viaja. Precios en francos CFP, sin centavos,
-- la misma moneda que Nueva Caledonia.
--
-- Es un territorio francés con moneda y reglas de entrada propias, y entra por
-- la decisión de la sección 16.2. Las ciudades del planificador son las de las
-- islas de la Sociedad —Tahití, Moorea, Bora Bora, Huahine, Raiatea y
-- Taha'a—, los atolones de Rangiroa y Fakarava, en las Tuamotu, y Nuku Hiva,
-- en las Marquesas, que tienen media hora menos que Tahití.
--
-- Calor húmedo todo el año, con la temporada de lluvias de noviembre a abril y
-- una más seca y fresca de mayo a octubre, la de los alisios. Las Tuamotu son
-- más secas que las islas altas. Bora Bora lleva el factor más alto que admite
-- el generador (2,5): sus hoteles sobre el agua cuestan bastante más.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Papeete (Tahití) en julio: 20,4 / 28,4 → templado + calido → nunca abrigo, playa
--   Papeete (Tahití) en marzo: 23 / 31,2 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000c700 a c708, la base es c700.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

