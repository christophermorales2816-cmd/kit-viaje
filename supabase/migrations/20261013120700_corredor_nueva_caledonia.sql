-- Nueva Caledonia, con Numea como ciudad base: es la capital y por donde
-- entra casi todo el que viaja. Precios en francos CFP, sin centavos: es la
-- moneda de los territorios franceses del Pacífico, atada al euro.
--
-- Es un territorio francés con moneda y reglas de entrada propias, y entra por
-- la decisión de la sección 16.2. Las ciudades del planificador son Numea, la
-- isla de los Pinos, las islas de la Lealtad —Lifou, Maré y Ouvéa—, Hienghène
-- y Poindimié en la costa este, Bourail y el parque de la Rivière Bleue.
--
-- Trópico del hemisferio sur, más fresco que el resto de la Melanesia: veranos
-- calurosos y húmedos de diciembre a marzo, con ciclones, e inviernos templados
-- de junio a agosto. La costa este llueve bastante más que la oeste.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Parque de la Rivière Bleue en agosto: 15 / 23,2 → fresco + templado → capas, cero playa
--   Bourail (La Roche Percée) en febrero: 22,4 / 30,2 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000c600 a c608, la base es c600.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

