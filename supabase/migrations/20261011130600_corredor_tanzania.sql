-- Tanzania, con Arusha como ciudad base: es la puerta de los safaris del norte
-- y por donde entra casi todo el que viaja, como Siem Reap en Camboya. Precios
-- en chelines tanzanos, sin centavos: un dólar son miles de chelines.
--
-- Hemisferio sur y muy cerca del ecuador: el año se ordena por la lluvia, no por
-- la temperatura. Las lluvias largas van de marzo a mayo —abril es el mes más
-- mojado en todo el país— y las cortas, en noviembre y diciembre. La temporada
-- seca, de junio a octubre, es la de los safaris. La altura manda en el norte:
-- Arusha y el Serengeti son templados, y en el borde del cráter del Ngorongoro,
-- a más de dos mil metros, las noches de julio rondan los cinco grados. Zanzíbar
-- y Dar es Salaam son calurosas y húmedas todo el año.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Cráter del Ngorongoro en julio: 5,4 / 16,4 → frio + fresco → abrigo, cero playa
--   Moshi (Kilimanjaro) en febrero: 16,8 / 32,8 → fresco + templado + calido → capas, playa
--
-- IDS FIJOS: destinos 00000000-…-000000009500 a 9508, la base es 9500.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

