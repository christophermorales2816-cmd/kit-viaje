-- Puerto Rico, con San Juan como ciudad base. Precios en dólares
-- estadounidenses, con centavos: la isla usa el dólar.
--
-- Calor parejo en la costa, más seco en el sur y el oeste, y dos excepciones:
-- El Yunque, el bosque lluvioso del este, y la cordillera central, más frescos
-- y lluviosos. Culebra y Vieques, más secas, se alcanzan en ferry o avioneta.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   La cordillera central en enero: 15,9 / 23,6 → fresco + templado → capas, cero playa
--   Ponce en agosto: 24,6 / 32,7 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000ef00 a ef08, la base es ef00.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

