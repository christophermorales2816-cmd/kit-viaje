-- Kirguistán, con Biskek como ciudad base. Precios en soms kirguises, sin
-- centavos: un dólar son casi noventa soms.
--
-- Casi todo el país es montaña. Biskek y Osh, en los valles, tienen veranos
-- calurosos e inviernos fríos. El lago Issyk-Kul, a mil seiscientos metros,
-- modera el clima de sus orillas: veranos templados, y la costa sur casi no
-- llueve. Más arriba el invierno es largo y duro: el lago Song-Kol, a más de
-- tres mil metros, está congelado de noviembre a abril, y los campamentos de
-- yurtas abren solo de junio a septiembre.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Lago Song-Kol en enero: -24 / -12 → frio → abrigo, cero playa
--   Osh en julio: 17,6 / 33 → fresco + templado + calido → capas, playa
--
-- IDS FIJOS: destinos 00000000-…-000000006700 a 6708, la base es 6700.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

