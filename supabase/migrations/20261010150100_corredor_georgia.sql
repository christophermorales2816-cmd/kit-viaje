-- lari vale menos de medio dólar, como el zloty.
--
-- El país cambia mucho en pocos kilómetros. Tiflis y Kajetia tienen veranos
-- calurosos y secos e inviernos fríos pero cortos; Batumi, sobre el mar Negro,
-- es subtropical y de las ciudades más lluviosas del Cáucaso. El Gran Cáucaso,
-- al norte, es otra cosa: Kazbegi y Mestia pasan el invierno bajo cero, y
-- Gudauri, la estación de esquí, a más de dos mil metros, tiene nieve de
-- diciembre a abril.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Gudauri en enero: -11,4 / -3 → frio → abrigo, cero playa
--   Tiflis en julio: 19,9 / 31,3 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000006200 a 6208, la base es 6200.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

