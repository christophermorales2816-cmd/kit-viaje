-- Benín, con Cotonú como ciudad base: es la ciudad más grande y la del
-- aeropuerto; Porto Novo, la capital, está a menos de una hora. Precios en
-- francos CFA de África Occidental, sin centavos, la misma moneda que Togo.
--
-- Las ciudades del planificador son las del sur y del centro: la costa, el lago
-- Nokoué, Abomey y las colinas de Dassa y Savalou. Ninguna está en el norte, en
-- el Atacora ni en el Alibori, adonde las recomendaciones de viaje piden no ir;
-- por eso no están la Pendjari ni el parque W. La guía lo dice como dato de
-- entrada.
--
-- Calor húmedo todo el año en la costa, con dos temporadas de lluvia: de abril
-- a julio, y en septiembre y octubre; en agosto llueve poco. Tierra adentro, en
-- Abomey, Dassa y Savalou, esa pausa casi no se nota, y el harmattan seca el
-- aire de diciembre a febrero.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Savalou en diciembre: 20,2 / 34 → templado + calido → nunca abrigo, playa
--   Savalou en febrero: 22,4 / 35,8 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000b700 a b708, la base es b700.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

