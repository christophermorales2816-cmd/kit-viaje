-- Tonga, con Nukualofa como ciudad base: es la capital, en Tongatapu, y por
-- donde entra casi todo el que viaja. Precios en pa'angas, sin centavos.
--
-- Las ciudades del planificador son las de Tongatapu —Nukualofa, el trilito de
-- Ha'amonga, la playa de Ha'atafu y los agujeros de Mapu'a 'a Vaea—, la isla
-- 'Eua y los grupos de Ha'apai y Vava'u, el de las ballenas.
--
-- Trópico del hemisferio sur: calor húmedo de diciembre a abril, la temporada
-- de lluvias y ciclones, y un invierno templado de junio a septiembre. Las
-- ballenas jorobadas llegan a criar de julio a octubre. Tonga está al oeste de
-- la línea de cambio de fecha: tiene trece horas más que Greenwich.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Isla 'Eua (acantilados y selva) en agosto: 17,4 / 23,8 → fresco + templado → capas, cero playa
--   Neiafu (Vava'u) en febrero: 24 / 30,2 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000c900 a c908, la base es c900.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

