-- Jamaica, con Montego Bay como ciudad base: es donde llega y duerme la
-- mayoría de los viajeros. Precios en dólares jamaiquinos, enteros: la unidad
-- vale menos de un centavo de dólar estadounidense.
--
-- Caribe todo el año en la costa, con la sorpresa de las Montañas Azules,
-- donde las noches son frescas. Entra con aviso (spec, 22): ninguna de las
-- nueve ciudades está en los barrios que los gobiernos desaconsejan.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Montañas Azules en febrero: 12 / 21,5 → fresco + templado → capas, cero playa
--   Treasure Beach en agosto: 24,8 / 32,9 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000e200 a e208, la base es e200.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

