-- Angola, con Luanda como ciudad base: es la capital y por donde entra casi
-- todo el que viaja. Precios en kwanzas, sin centavos.
--
-- Las ciudades del planificador son Luanda y su costa, Kalandula, Benguela, el
-- sur —Lubango y Namibe— y el parque de Iona. Ninguna está en Cabinda, el
-- enclave del norte, ni en las Lundas, las provincias de los diamantes, donde
-- varias recomendaciones de viaje piden más precaución; la guía lo dice como
-- dato de entrada.
--
-- Hemisferio sur. La costa es seca por la corriente de Benguela: Luanda tiene
-- un verano caluroso con algo de lluvia, de enero a abril, y un invierno
-- fresco y nublado, el cacimbo, de junio a septiembre. Hacia el sur, en Namibe
-- y en Iona, empieza el desierto. Las tierras altas, en Lubango y Kalandula,
-- tienen lluvias de octubre a abril; en Lubango, las noches de julio bajan a
-- seis grados.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Lubango (Serra da Leba) en julio: 6 / 24,4 → frio + fresco + templado → abrigo, cero playa
--   Parque Nacional de Iona en febrero: 20 / 32,6 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000b200 a b208, la base es b200.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

