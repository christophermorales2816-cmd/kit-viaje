-- Kazajistán, con Almaty como ciudad base. Precios en tenges, sin centavos: un
-- dólar son varios cientos de tenges.
--
-- La base es Almaty y no Astaná, la capital, como Dubái en vez de Abu Dabi: es
-- por donde entra y desde donde sale casi todo el que viaja, a las montañas,
-- los lagos y los cañones del sudeste.
--
-- El país es enorme y continental. Almaty, al pie de las montañas, tiene
-- inviernos fríos y veranos calurosos; Astaná y Burabay, en la estepa del
-- norte, tienen de los inviernos más fríos del planificador, con máximas bajo
-- cero de noviembre a marzo. Turkestán y Shymkent, en el sur, son calurosos y
-- secos en verano. Shymbulak, a más de dos mil metros, es la estación de
-- esquí de Almaty.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Burabay (Borovoe) en enero: -20,4 / -11,6 → frio → abrigo, cero playa
--   Turkestán en julio: 21,6 / 37,4 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000006600 a 6608, la base es 6600.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

