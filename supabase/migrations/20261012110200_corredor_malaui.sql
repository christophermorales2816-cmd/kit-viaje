-- Malaui, con Lilongwe como ciudad base: es la capital y por donde entra casi
-- todo el que viaja.
--
-- Precios en DÓLARES, con centavos, aunque la moneda sea el kwacha. Es el caso
-- de Turkmenistán, Irán y Myanmar: la cotización oficial y la del mercado
-- paralelo están muy lejos, y un precio en kwachas convertido a la oficial
-- diría un costo que el viajero no paga. El corredor sigue en kwachas, con las
-- dos cotizaciones, porque eso es lo que la guía explica.
--
-- Hemisferio sur, con lluvias de noviembre a abril y un invierno seco de mayo a
-- agosto, de noches frías en la meseta. El lago y el valle del Shire son
-- calurosos casi todo el año; octubre, antes de las lluvias, es el mes más
-- caluroso. La meseta de Nyika, a más de dos mil metros, es lo más frío del
-- país: en julio, las noches bajan a dos grados.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Meseta de Nyika en julio: 2,4 / 14,6 → frio + fresco → abrigo, cero playa
--   Parque Nacional Liwonde en octubre: 20,6 / 34,6 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000009f00 a 9f08, la base es 9f00.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

