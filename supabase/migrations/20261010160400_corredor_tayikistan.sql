-- un dólar son unos diez somonis.
--
-- Más del noventa por ciento del país es montaña. Dusambé y Juyand, en los
-- valles, tienen veranos muy calurosos y secos e inviernos fríos y lluviosos.
-- Las montañas de Fann, con Iskanderkul y los Siete Lagos, a más de dos mil
-- metros, son frescas en verano y nevadas en invierno. El Pamir, con Murgab y
-- el lago Karakul a más de tres mil quinientos metros, es desierto de altura:
-- casi no llueve y el invierno es de los más fríos del planificador.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
