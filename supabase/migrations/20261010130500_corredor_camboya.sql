-- Camboya, con Siem Reap como ciudad base. Precios en dólares, con centavos.
--
-- En Camboya al viajero se le cobra en dólares y el riel es el vuelto: el
-- corredor sigue en rieles, porque es la moneda del país, y los precios van en
-- dólares, igual que en Venezuela y Cuba. La base es Siem Reap y no Phnom Penh,
-- como Antigua en Guatemala: es donde se duerme para ver Angkor.
--
-- Calor todo el año. La estación seca va de noviembre a abril —abril es el mes
-- más caluroso— y la de lluvias, de mayo a octubre, con chaparrones fuertes por
-- la tarde. Mondulkiri, en la meseta del este, tiene noches frescas.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Mondulkiri en enero: 15,6 / 28 → fresco + templado + calido → capas, playa
--   Kratie en abril: 25,4 / 36,2 → calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000005a00 a 5a08, la base es 5a00.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

