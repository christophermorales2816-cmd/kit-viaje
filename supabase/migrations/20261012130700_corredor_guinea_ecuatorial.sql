-- Guinea Ecuatorial, con Malabo como ciudad base: es la capital, en la isla de
-- Bioko, y por donde entra casi todo el que viaja. Precios en francos CFA de
-- África Central, sin centavos. Es el único país de África donde el español es
-- idioma oficial.
--
-- Las ciudades del planificador son las de Bioko —Malabo, Sipopo, Luba, Ureca y
-- Moka— y las del continente: Bata, Mbini, el parque de Monte Alén y la isla de
-- Corisco.
--
-- Sobre el ecuador: calor húmedo todo el año. Malabo tiene su temporada seca
-- de diciembre a febrero; el sur de Bioko, en Ureca, es de los lugares más
-- lluviosos del mundo, y Moka, a más de mil metros, es fresco. En el
-- continente, como en Gabón, la temporada seca va de junio a agosto.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Moka (tierras altas de Bioko) en enero: 14,6 / 23,4 → fresco + templado → capas, cero playa
--   Malabo en febrero: 20,6 / 31,4 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000b400 a b408, la base es b400.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

