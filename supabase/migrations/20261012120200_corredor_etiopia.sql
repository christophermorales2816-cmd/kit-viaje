-- Etiopía, con Adís Abeba como ciudad base: es la capital y por donde entra
-- casi todo el que viaja. Precios en birrs, sin centavos.
--
-- Entra con aviso (spec, 15.8): la guía manda a revisar la recomendación de
-- viaje del propio país antes de reservar. Las ciudades del planificador son la
-- capital, el sur y el este; ninguna está en Amhara, Tigray, Afar ni Oromía.
-- Lalibela, Gondar, Axum y el desierto de Danakil quedan afuera, y también los
-- lagos del Rift al sur de la capital, en zonas de Oromía que las
-- recomendaciones desaconsejan. Al sur y al este conviene llegar en avión.
--
-- Clima de altura: Adís Abeba, a más de dos mil trescientos metros, tiene días
-- templados y noches frescas todo el año, con la lluvia larga, el kiremt, de
-- junio a septiembre. El sur tiene lluvias en abril y mayo y otra vez en
-- octubre; los montes Gamo, en Dorze, son frescos todo el año, y el valle del
-- Omo y Dire Dawa, en el este, son lo más caluroso.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Adís Abeba en diciembre: 8 / 22,4 → frio + fresco + templado → abrigo, cero playa
--   Dire Dawa en junio: 21,4 / 34,8 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000a700 a a708, la base es a700.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

