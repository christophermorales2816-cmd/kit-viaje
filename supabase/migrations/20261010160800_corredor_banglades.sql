-- Bangladés, con Daca como ciudad base. Precios en takas, sin centavos: un
-- dólar son más de cien takas.
--
-- Llanura tropical de ríos y deltas, con monzón. De noviembre a febrero es la
-- época seca y templada, con mañanas frescas en el norte. Marzo y abril son muy
-- calurosos y húmedos, y de junio a septiembre el monzón trae lluvia casi todos
-- los días e inundaciones. Sylhet y Srimangal, en el noreste, son de lo más
-- lluvioso del país; Cox's Bazar y la isla de San Martín, sobre el golfo de
-- Bengala, tienen el mar templado todo el año.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Srimangal en enero: 10,6 / 24,4 → fresco + templado → capas, cero playa
--   Paharpur en abril: 22 / 35 → templado + calido → nunca abrigo, playa
--
