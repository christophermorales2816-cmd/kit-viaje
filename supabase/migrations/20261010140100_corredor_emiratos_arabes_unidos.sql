-- Emiratos Árabes Unidos, con Dubái como ciudad base. Precios en dírhams, sin
-- centavos: el dírham vale un cuarto de dólar, como el zloty.
--
-- La base es Dubái y no Abu Dabi, como Antigua en Guatemala: es por donde entra
-- y donde duerme casi todo el que viaja.
--
-- Desierto junto al mar: de noviembre a marzo, días templados y noches frescas;
-- de mayo a septiembre, calor extremo, con máximas de más de cuarenta grados y
-- noches de cerca de treinta en la costa. Casi no llueve. Jebel Jais, a casi
-- dos mil metros, es la excepción: en invierno puede helar.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Jebel Jais en enero: 4,6 / 13 → frio + fresco → abrigo, cero playa
--   Oasis de Liwa en julio: 28,6 / 45 → calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000005c00 a 5c08, la base es 5c00.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

