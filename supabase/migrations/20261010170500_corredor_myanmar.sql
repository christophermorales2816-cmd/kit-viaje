-- Myanmar, con Rangún como ciudad base. Precios en DÓLARES, no en kyats: el
-- kyat tiene una cotización oficial y otra de mercado muy lejos entre sí, y con
-- la inflación un precio en kyats quedaría viejo en semanas. Mismo criterio que
-- Venezuela y Cuba.
--
-- Entra con aviso (spec, 14.11): la guía manda a revisar la recomendación de
-- viaje del propio país antes de reservar. Las ciudades del planificador son
-- las de la ruta habitual; ninguna está en Rakhine ni en el norte del estado
-- Shan.
--
-- Tropical con monzón. De noviembre a febrero es la época seca y templada; marzo
-- y abril, muy calurosos, con más de treinta y cinco grados en Bagan y
-- Mandalay; de junio a septiembre llueve casi todos los días en la costa y en
-- Rangún. Bagan y Mandalay, en la zona seca del centro, reciben menos lluvia.
-- El lago Inle y Kalaw, a más de ochocientos metros, tienen noches frescas en
-- invierno.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Kalaw en enero: 6,6 / 22,4 → frio + fresco + templado → abrigo, cero playa
--   Bagan en abril: 25,6 / 39 → calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000007700 a 7708, la base es 7700.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

