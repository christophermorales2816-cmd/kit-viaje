-- Chipre, con Limasol como ciudad base. Precios en euros, con centavos.
--
-- El Mediterráneo más oriental: veranos largos, secos y muy calurosos —Nicosia,
-- tierra adentro, pasa los treinta y cinco grados— e inviernos suaves y algo
-- lluviosos en la costa. Los montes Troodos son el contraste: noches frescas en
-- verano y nieve en las cumbres en invierno. Todas las ciudades están en la
-- parte de la isla que administra la República de Chipre.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Montes Troodos en febrero: 1,4 / 9,6 → frio → abrigo, cero playa
--   Nicosia en julio: 22,4 / 37,6 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000004500 a 4508, la base es 4500.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

