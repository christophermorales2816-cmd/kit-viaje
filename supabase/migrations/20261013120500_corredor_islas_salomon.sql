-- Islas Salomón, con Honiara como ciudad base: es la capital, en
-- Guadalcanal, y por donde entra casi todo el que viaja. Precios en dólares
-- salomonenses, sin centavos.
--
-- Las ciudades del planificador son Honiara, las islas Florida y Savo, Malaita,
-- las islas Russell y la Provincia Occidental: Munda, Gizo, la laguna Marovo y
-- Tetepare.
--
-- Calor húmedo todo el año, con lluvias casi todos los días en la Provincia
-- Occidental. Honiara, en la costa norte de Guadalcanal, es más seca de junio a
-- octubre, y de noviembre a abril es la temporada de ciclones.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Auki (Malaita) en julio: 21,6 / 30 → templado + calido → nunca abrigo, playa
--   Honiara en octubre: 22,2 / 31,6 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000c400 a c408, la base es c400.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

