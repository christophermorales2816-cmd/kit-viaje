-- Ghana, con Accra como ciudad base: es la capital y por donde entra casi todo
-- el que viaja. Precios en cedis, sin centavos.
--
-- Calor húmedo todo el año, con dos temporadas de lluvia en el sur: la larga,
-- de abril a junio, y la corta, de septiembre a noviembre. Accra es de lo más
-- seco de la costa; hacia el oeste, en Busua, y tierra adentro, en Kakum y
-- Kumasi, llueve bastante más. De diciembre a febrero sopla el harmattan, el
-- viento del Sahara, que trae polvo y cielos blancos.
--
-- Las ciudades son las del sur y del centro, las de los viajes habituales.
-- Ninguna está en el norte, donde partes de las regiones fronterizas tienen
-- recomendaciones de viaje de más precaución.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Aburi (jardín botánico) en agosto: 19,8 / 24,6 → templado → nunca abrigo, cero playa
--   Cataratas de Wli (Hohoe) en febrero: 22,4 / 34,4 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-00000000a000 a a008, la base es a000.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

