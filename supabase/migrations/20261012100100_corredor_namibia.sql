-- Namibia, con Windhoek como ciudad base: es la capital y por donde entra casi
-- todo el que viaja. Precios en dólares namibios, sin centavos: valen lo mismo
-- que el rand, que también se acepta en todo el país.
--
-- Desierto con estaciones al revés. Windhoek, en la meseta, tiene veranos
-- calurosos con tormentas e inviernos secos de noches frías. El Namib, en
-- Sossusvlei, pasa los treinta y cinco grados en verano y baja a cinco en las
-- noches de julio. La costa —Swakopmund, Lüderitz— es fresca y con niebla todo
-- el año por la corriente fría de Benguela, y casi no llueve. El noreste, sobre
-- el Zambeze, es lo único con lluvias de verano de verdad.
--
-- Lo que resuelve el motor con estos números, contra los umbrales sembrados
-- (frio ≤10, fresco ≤18, templado ≤25, calido sin tope):
--
--   Kalahari (Mariental) en julio: 3 / 21 → frio + fresco + templado → abrigo, cero playa
--   Cañón del río Fish (Ai-Ais) en enero: 21 / 38,5 → templado + calido → nunca abrigo, playa
--
-- IDS FIJOS: destinos 00000000-…-000000009600 a 9608, la base es 9600.
-- Los precios usan md5(destino || nombre)::uuid, igual que las ciudades
-- derivadas de las migraciones anteriores: determinístico y sin choques.

